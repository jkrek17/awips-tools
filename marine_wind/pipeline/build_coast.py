#!/usr/bin/env python3
"""Write the page's coastlines from Natural Earth 50m land (public domain), outer rings
only, rounded to 0.01 degree:
    page/coast.js       North Atlantic box  (window.MW_COAST)
    page/coast_npac.js  North Pacific box   (window.MW_COAST_NPAC), longitudes 0..360
                        so the box runs continuously across the date line

    python3 marine_wind/pipeline/build_coast.py
"""
import json
import os
import urllib.request

SRC = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson"
PAGE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "page")
# (box with a margin around the grid, output file, JS variable, shift west longitudes by 360)
TARGETS = [((-105.0, 13.0, 20.0, 72.0), "coast.js", "MW_COAST", False),
           ((125.0, 13.0, 255.0, 72.0), "coast_npac.js", "MW_COAST_NPAC", True)]


def clip(ring, box):
    """Sutherland-Hodgman clip of one ring to the box (x0, y0, x1, y1)."""
    x0, y0, x1, y1 = box
    edges = [(lambda p: p[0] >= x0, lambda a, b: (x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[0] <= x1, lambda a, b: (x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[1] >= y0, lambda a, b: (a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0)),
             (lambda p: p[1] <= y1, lambda a, b: (a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1))]
    pts = [tuple(c) for c in ring]
    for inside, cut in edges:
        if not pts:
            break
        out, prev = [], pts[-1]
        for cur in pts:
            if inside(cur):
                if not inside(prev):
                    out.append(cut(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cut(prev, cur))
            prev = cur
        pts = out
    return pts


def main():
    with urllib.request.urlopen(SRC, timeout=120) as r:
        gj = json.load(r)
    for box, name, var, shift in TARGETS:
        write(gj, box, os.path.join(PAGE, name), var, shift)


def write(gj, BOX, OUT, var, shift):
    rings = []
    for f in gj["features"]:
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for p in polys:
            ring = p[0]
            if shift:     # Natural Earth splits rings at 180, so each ring is all-east or all-west
                if sum(c[0] for c in ring) / len(ring) < 0:
                    ring = [[c[0] + 360, c[1]] for c in ring]
            xs, ys = [c[0] for c in ring], [c[1] for c in ring]
            if max(xs) < BOX[0] or min(xs) > BOX[2] or max(ys) < BOX[1] or min(ys) > BOX[3]:
                continue
            out = []
            for x, y in clip(ring, BOX):
                pt = [round(x, 2), round(y, 2)]
                if not out or out[-1] != pt:
                    out.append(pt)
            if len(out) >= 4:
                rings.append(out)
    with open(OUT, "w") as f:
        f.write("/* generated by marine_wind/pipeline/build_coast.py - do not edit */\n")
        f.write("/* Natural Earth 50m land, public domain. */\n")
        f.write("window.%s = %s;\n" % (var, json.dumps(rings, separators=(",", ":"))))
    print(len(rings), "rings ->", OUT, os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
